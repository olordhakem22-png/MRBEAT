CREATE TABLE IF NOT EXISTS users (
id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
username VARCHAR(50) NOT NULL UNIQUE,
email VARCHAR(190) NULL UNIQUE,
password_hash VARCHAR(255) NOT NULL,
role ENUM('user','admin','seller','support') NOT NULL DEFAULT 'user',
status ENUM('active','blocked') NOT NULL DEFAULT 'active',
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS wallets (
user_id BIGINT UNSIGNED PRIMARY KEY,
balance_mb DECIMAL(18,2) NOT NULL DEFAULT 0,
balance_usdt DECIMAL(18,2) NOT NULL DEFAULT 0,
updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT fk_wallet_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS products (
id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
name VARCHAR(190) NOT NULL,
price_mb DECIMAL(18,2) NOT NULL DEFAULT 0,
price_usdt DECIMAL(18,2) NOT NULL DEFAULT 0,
currency_mode ENUM('mb','usdt','both') NOT NULL DEFAULT 'mb',
stock_type ENUM('email','rdp') NOT NULL DEFAULT 'rdp',
image_url VARCHAR(500) NULL,
description TEXT NULL,
is_active TINYINT(1) NOT NULL DEFAULT 1,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product_stock (
id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
product_id BIGINT UNSIGNED NOT NULL,
type ENUM('email','rdp') NOT NULL,
email VARCHAR(190) NULL,
pass VARCHAR(190) NULL,
host VARCHAR(190) NULL,
user VARCHAR(190) NULL,
status ENUM('available','sold') NOT NULL DEFAULT 'available',
sold_to_user_id BIGINT UNSIGNED NULL,
sold_order_id BIGINT UNSIGNED NULL,
sold_at TIMESTAMP NULL,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT fk_stock_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
CONSTRAINT fk_stock_sold_user FOREIGN KEY (sold_to_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS orders (
id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
user_id BIGINT UNSIGNED NOT NULL,
total_mb DECIMAL(18,2) NOT NULL DEFAULT 0,
total_usdt DECIMAL(18,2) NOT NULL DEFAULT 0,
currency ENUM('mb','usdt') NOT NULL DEFAULT 'mb',
status ENUM('paid','refunded') NOT NULL DEFAULT 'paid',
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS order_items (
id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
order_id BIGINT UNSIGNED NOT NULL,
product_id BIGINT UNSIGNED NOT NULL,
qty INT NOT NULL DEFAULT 1,
unit_price_mb DECIMAL(18,2) NOT NULL DEFAULT 0,
unit_price_usdt DECIMAL(18,2) NOT NULL DEFAULT 0,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT fk_item_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS transactions (
id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
user_id BIGINT UNSIGNED NOT NULL,
admin_id BIGINT UNSIGNED NULL,
kind ENUM('credit','debit') NOT NULL,
currency ENUM('mb','usdt') NOT NULL,
amount DECIMAL(18,2) NOT NULL,
reason VARCHAR(255) NOT NULL,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT fk_tx_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
CONSTRAINT fk_tx_admin FOREIGN KEY (admin_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS settings (
k VARCHAR(100) PRIMARY KEY,
v TEXT NULL,
updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

